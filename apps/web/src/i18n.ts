export function initialLang(): Lang {
  try {
    const stored = localStorage.getItem('navbat-lang');
    if (isLang(stored)) return stored;
  } catch {
    /* ignore */
  }
  const q = new URLSearchParams(window.location.search).get('lang');
  if (isLang(q)) return q;
  return langFromTelegram(window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code ?? navigator.language);
}

export interface I18n {
  lang: Lang;
  t: Dict;
  setLang(l: Lang): void;
}

export const I18nContext = createContext<I18n>({ lang: 'uz', t: uz, setLang: () => undefined });

export const useI18n = () => useContext(I18nContext);

export function errorText(t: Dict, e: unknown): string {
  const code = (e as { code?: string })?.code;
  if (code && t.errors[code]) return t.errors[code]!;
  if (e instanceof TypeError) return t.errors.NETWORK!;
  return (e as Error)?.message ?? String(e);
}
